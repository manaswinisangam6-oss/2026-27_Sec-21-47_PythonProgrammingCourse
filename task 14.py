# Demonstrate operator precedence and associativity

# Operator precedence
result1 = 10 + 5 * 2
print("10 + 5 * 2 =", result1)

# Parentheses have higher precedence
result2 = (10 + 5) * 2
print("(10 + 5) * 2 =", result2)

# Associativity of arithmetic operators
result3 = 20 - 5 - 3
print("20 - 5 - 3 =", result3)

# Right-to-left associativity of exponentiation
result4 = 2 ** 3 ** 2
print("2 ** 3 ** 2 =", result4)
# Python program to demonstrate type conversion

# String to integer
a = "10"
b = int(a)
print("String to Integer:", b, type(b))

# Integer to float
c = 20
d = float(c)
print("Integer to Float:", d, type(d))

# Float to integer
e = 15.5
f = int(e)
print("Float to Integer:", f, type(f))

# Integer to string
g = 25
h = str(g)
print("Integer to String:", h, type(h))